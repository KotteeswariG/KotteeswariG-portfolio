import { useTheme } from "../hooks/useTheme";

type Props = {
  inline?: boolean;
};

function SunIcon() {
  return (
    <svg
      viewBox="0 0 24 24"
      width="18"
      height="18"
      fill="none"
      stroke="currentColor"
      strokeWidth="2"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
    >
      <circle cx="12" cy="12" r="4" />
      <path d="M12 2v2" />
      <path d="M12 20v2" />
      <path d="M4.93 4.93l1.41 1.41" />
      <path d="M17.66 17.66l1.41 1.41" />
      <path d="M2 12h2" />
      <path d="M20 12h2" />
      <path d="M6.34 17.66l-1.41 1.41" />
      <path d="M19.07 4.93l-1.41 1.41" />
    </svg>
  );
}

function MoonIcon() {
  return (
    <svg
      viewBox="0 0 24 24"
      width="18"
      height="18"
      fill="none"
      stroke="currentColor"
      strokeWidth="2"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
    >
      <path d="M21 12.79A9 9 0 1 1 11.21 3 7 7 0 0 0 21 12.79z" />
    </svg>
  );
}

export function ThemeToggle({ inline = false }: Props) {
  const { theme, toggle, mounted } = useTheme();
  const isDark = theme === "dark";
  const label = isDark ? "Switch to light theme" : "Switch to dark theme";

  return (
    <button
      type="button"
      className={`theme-toggle${inline ? " theme-toggle-inline" : ""}`}
      onClick={toggle}
      aria-label={label}
      title={label}
      aria-pressed={isDark}
      suppressHydrationWarning
    >
      <span className="theme-toggle-icon" suppressHydrationWarning>
        {isDark ? <SunIcon /> : <MoonIcon />}
      </span>
      <span className="visually-hidden">
        {mounted ? label : "Toggle theme"}
      </span>
    </button>
  );
}
